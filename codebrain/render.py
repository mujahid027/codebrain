# Markdown -> HTML (small, dependency-free) for a friendly browser page
# ----------------------------------------------------------------------------
def _inline(text):
    text = html.escape(text, quote=False)
    text = re.sub(r"`([^`]+)`", r"<code>\1</code>", text)      # `inline code`
    text = re.sub(r"\*\*([^*]+)\*\*", r"<strong>\1</strong>", text)  # **bold**
    return text


def markdown_to_html(md):
    """Enough Markdown for LLM output: headings, bold, code, lists, paragraphs."""
    out, para, code_buf = [], [], []
    in_code = False
    list_open = None

    def flush_para():
        if para:
            out.append("<p>" + _inline(" ".join(para)) + "</p>")
            para.clear()

    def close_list():
        nonlocal list_open
        if list_open:
            out.append(f"</{list_open}>")
            list_open = None

    for line in md.split("\n"):
        stripped = line.strip()

        if stripped.startswith("```"):
            if in_code:
                out.append("<pre><code>" + html.escape("\n".join(code_buf)) + "</code></pre>")
                code_buf.clear()
                in_code = False
            else:
                flush_para(); close_list()
                in_code = True
            continue
        if in_code:
            code_buf.append(line)
            continue

        if not stripped:
            flush_para(); close_list()
            continue

        if re.fullmatch(r"(-{3,}|\*{3,}|_{3,})", stripped):   # horizontal rule
            flush_para(); close_list()
            out.append("<hr>")
            continue

        m = re.match(r"(#{1,6})\s+(.*)", stripped)
        if m:
            flush_para(); close_list()
            level = len(m.group(1))
            out.append(f"<h{level}>{_inline(m.group(2))}</h{level}>")
            continue

        m = re.match(r"[-*]\s+(.*)", stripped)
        if m:
            flush_para()
            if list_open != "ul":
                close_list(); out.append("<ul>"); list_open = "ul"
            out.append("<li>" + _inline(m.group(1)) + "</li>")
            continue

        m = re.match(r"\d+\.\s+(.*)", stripped)
        if m:
            flush_para()
            if list_open != "ol":
                close_list(); out.append("<ol>"); list_open = "ol"
            out.append("<li>" + _inline(m.group(1)) + "</li>")
            continue

        close_list()
        para.append(stripped)

    if in_code:
        out.append("<pre><code>" + html.escape("\n".join(code_buf)) + "</code></pre>")
    flush_para(); close_list()
    return "\n".join(out)


