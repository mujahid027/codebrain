"""Turn a Project into human-readable output: a terminal tour, a Markdown file,
or a clean formatted HTML page for the browser.

Both read the already-built brain (codebrain.scan.Project) - no analysis here.
"""

import html
import os
import re
from collections import defaultdict

from .scan import FOLDER_HINTS


def describe_folder(name):
    return FOLDER_HINTS.get(name.lower())


def human_list(items, limit=8):
    items = list(items)
    if not items:
        return ""
    shown = items[:limit]
    extra = len(items) - len(shown)
    s = ", ".join(shown)
    if extra > 0:
        s += f", ...(+{extra} more)"
    return s


def _top_level_folders(project):
    """{top_dir: total_files_beneath} + recognizable sub-folders, from files_by_dir."""
    top_counts = defaultdict(int)
    for d, fs in project.files_by_dir.items():
        if d == ".":
            continue
        top = d.split(os.sep)[0]
        top_counts[top] += len(fs)
    return top_counts


def _external_deps(fileinfo):
    """Imports that look like external packages (not relative, not resolved)."""
    return [i for i in fileinfo.imports if not i.startswith(".")]


# ----------------------------------------------------------------------------
# Terminal tour (plain text)
# ----------------------------------------------------------------------------
def render_terminal(project):
    out = []
    w = out.append

    w("=" * 70)
    w(f"  UNDERSTANDING:  {project.name}")
    w("=" * 70)

    # Tech stack
    w("\n## What kind of project is this?\n")
    if project.stack:
        for desc, manifest in project.stack:
            w(f"  - {desc}   (found `{manifest}`)")
    else:
        w("  - Couldn't find a manifest file - guessing from the code files below.")

    exts = defaultdict(int)
    for f in project.files:
        exts[f.lang] += 1
    if exts:
        w("\n  Main languages by file count:")
        for ext, n in sorted(exts.items(), key=lambda x: -x[1])[:6]:
            w(f"    {ext:6}  {n} files")

    # Folder guide
    w("\n## Your folders - what each one is for\n")
    root_files = project.files_by_dir.get(".", [])
    if root_files:
        w(f"  (root)/         top-level files: {human_list(root_files)}")
    top_counts = _top_level_folders(project)
    for d in sorted(top_counts):
        hint = describe_folder(d)
        label = f"  {d}/".ljust(16)
        if hint:
            w(f"{label}{hint}  ({top_counts[d]} files)")
        else:
            w(f"{label}(contains {top_counts[d]} files)")
        subs = sorted({
            p for p in project.files_by_dir
            if p != "." and p.split(os.sep)[0] == d and os.sep in p
        })
        for sub in subs:
            subhint = describe_folder(os.path.basename(sub))
            if subhint:
                w(f"      {sub}/".ljust(28) + f"-> {subhint}")

    # Entry points
    w("\n## Where does it start? (entry point)\n")
    if project.entry_points:
        for f in project.entry_points[:5]:
            extra = f"  -> defines: {human_list(f.funcs, 5)}" if f.funcs else ""
            w(f"  When you run this app, it likely starts at:  {f.rel}{extra}")
    else:
        w("  Couldn't spot an obvious entry file. Look for the file you run to start it.")

    # File by file
    w("\n## File-by-file: what each code file does\n")
    if not project.files:
        w("  No readable code files found.")
    for f in project.files:
        w(f"  {f.rel}   ({f.lines} lines)")
        if f.doc:
            w(f"      note: {f.doc}")
        if f.classes:
            w(f"      defines classes: {human_list(f.classes)}")
        if f.funcs:
            w(f"      functions: {human_list(f.funcs)}")
        deps = _external_deps(f)
        if deps:
            w(f"      uses: {human_list(deps, 6)}")
        w("")

    w("=" * 70)
    w("  That's the tour. Ask me about any file or folder above.")
    w("=" * 70)
    return "\n".join(out)


# ----------------------------------------------------------------------------
# Markdown tour (for --save)
# ----------------------------------------------------------------------------
def render_markdown(project):
    out = []
    w = out.append

    w(f"# {project.name} - project tour")
    w("")
    w("_Auto-generated by codebrain. Re-run to refresh._")
    w("")

    # Tech stack
    w("## What kind of project is this?")
    w("")
    if project.stack:
        w("| Tech | Detected from |")
        w("|---|---|")
        for desc, manifest in project.stack:
            w(f"| {desc} | `{manifest}` |")
    else:
        w("Couldn't find a manifest file - inferred from the code files below.")
    w("")

    exts = defaultdict(int)
    for f in project.files:
        exts[f.lang] += 1
    if exts:
        w("**Main languages by file count:** " + ", ".join(
            f"`{ext}` ({n})" for ext, n in sorted(exts.items(), key=lambda x: -x[1])[:6]
        ))
        w("")

    # Folder guide
    w("## Your folders - what each one is for")
    w("")
    root_files = project.files_by_dir.get(".", [])
    if root_files:
        w(f"- **(root)/** - top-level files: {human_list(root_files)}")
    top_counts = _top_level_folders(project)
    for d in sorted(top_counts):
        hint = describe_folder(d) or f"contains {top_counts[d]} files"
        w(f"- **{d}/** - {hint}  _({top_counts[d]} files)_")
        subs = sorted({
            p for p in project.files_by_dir
            if p != "." and p.split(os.sep)[0] == d and os.sep in p
        })
        for sub in subs:
            subhint = describe_folder(os.path.basename(sub))
            if subhint:
                w(f"  - `{sub.replace(os.sep, '/')}/` - {subhint}")
    w("")

    # Entry points
    w("## Where does it start? (entry point)")
    w("")
    if project.entry_points:
        for f in project.entry_points[:5]:
            extra = f" - defines `{human_list(f.funcs, 5)}`" if f.funcs else ""
            w(f"- `{f.rel}`{extra}")
    else:
        w("Couldn't spot an obvious entry file.")
    w("")

    # File by file
    w("## File-by-file: what each code file does")
    w("")
    for f in project.files:
        w(f"### `{f.rel}` _({f.lines} lines)_")
        if f.doc:
            w(f"> {f.doc}")
        if f.classes:
            w(f"- **classes:** {human_list(f.classes)}")
        if f.funcs:
            w(f"- **functions:** {human_list(f.funcs)}")
        deps = _external_deps(f)
        if deps:
            w(f"- **uses:** {human_list(deps, 8)}")
        w("")

    return "\n".join(out)


