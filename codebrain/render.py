def render_report_html(title, markdown_text, subtitle=""):
    body = markdown_to_html(markdown_text)
    tag = f'<div class="tag">{html.escape(subtitle)}</div>' if subtitle else ""
    return (
        "<!doctype html><html><head><meta charset='utf-8'>"
        "<meta name='viewport' content='width=device-width, initial-scale=1'>"
        f"<title>{html.escape(title)}</title><style>{_PAGE_CSS}</style></head>"
        f"<body><main>{tag}<h1>{html.escape(title)}</h1>{body}</main></body></html>"
    )
